        return "<?php\n"
            . "\n"
            . "declare(strict_types=1);\n"
            . "\n"
            . "namespace App\\Models\\Base;\n"
            . "\n"
            . "use Phalcon\\Mvc\\Model;\n"
            . "\n"
            . "/**\n"
