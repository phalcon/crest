    public function testADeclaredModelPathIsUsed(): void
    {
        // A project that keeps its classes in app/. A stub with a fixed
        // namespace fails here.
        $this->writeComposerJson(['Shop\\' => 'app/']);
        $this->writeCrestPhp(
            "['flavor' => 'mvc', 'bootstrap' => \\" . DatabaseFront::class . '::class, '
            . "'paths' => ['model' => 'app/Entities']]"
        );

        $status = $this->runCommand(['users']);

        $this->assertSame(0, $status);
        $this->assertStringContainsString(
            "namespace Shop\\Entities\\Base;\n",
            (string) file_get_contents($this->root . '/app/Entities/Base/UsersBase.php')
        );
        $this->assertStringContainsString(
            "use Shop\\Entities\\Base\\UsersBase;\n",
            (string) file_get_contents($this->root . '/app/Entities/Users.php')
        );
    }

    public function testADroppedAliasIsReported(): void
    {
        // The key column of invoices gets a new name, so the attribute of the
        // old key is dropped, and crest says so.
        $this->createTables(CustomersMigration::class, InvoicesMigration::class);
        $this->runCommand(['invoices']);
        $this->migration(InvoicesMigration::class)->drop();
        $this->createTables(InvoicesWithBuyerMigration::class);
        $this->freshStreams();

        $status = $this->runCommand(['invoices']);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Updated ' . $this->root . '/src/Models/Base/InvoicesBase.php' . PHP_EOL
            . "Dropped the alias Customer of 'belongsTo invoices(customer_id) -> customers(id)': "
            . 'the database has no such key' . PHP_EOL
            . 'Kept ' . $this->root . '/src/Models/Invoices.php: it exists; pass --force to replace it' . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testAKeyColumnWithAQuoteSkipsTheRelation(): void
    {
        // The key column of notes has a quote, so it is not a usable property
        // name, and notes has no PropertyName attribute for it. The relation
        // is skipped (#53, spec 3.4), and the base of users stays valid PHP.
        $this->createTables(NotesWithQuoteMigration::class);

        $status = $this->runCommand(['users']);
        $base   = (string) file_get_contents($this->root . self::BASE);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Created ' . $this->root . self::BASE . PHP_EOL
            . "Skipped the relation hasMany notes(it's_id) -> users(id): "
            . "column 'it's_id' of table 'notes' has no usable property name" . PHP_EOL
            . 'Created ' . $this->root . self::USERS . PHP_EOL,
            $this->readStdout()
        );
        $this->assertStringNotContainsString('hasMany', $base);
        $this->assertNotEmpty(token_get_all($base, TOKEN_PARSE));
    }

    public function testAMissingTableStops(): void
    {
        $this->assertStops(['nothing'], "table 'nothing' was not found in the database of the 'db' service");
    }

    public function testANewKeyUpdatesTheBaseOfTheReferencedTable(): void
    {
        // Spec 3.7: when another table gets a key to customers, a second run
        // on customers writes the new hasMany().
        $this->createTables(CustomersMigration::class);
        $this->runCommand(['customers']);
        $this->createTables(PaymentsMigration::class);
        $this->freshStreams();

        $status = $this->runCommand(['customers']);

        $this->assertSame(0, $status);
        $this->assertStringContainsString(
            "        \$this->hasMany(\n"
            . "            'id',\n"
            . "            \\App\\Models\\Payments::class,\n"
            . "            'customer_id',\n"
            . "            ['alias' => 'Payments']\n"
            . "        );\n",
            (string) file_get_contents($this->root . '/src/Models/Base/CustomersBase.php')
        );
        $this->assertSame(
            'Updated ' . $this->root . '/src/Models/Base/CustomersBase.php' . PHP_EOL
            . 'Kept ' . $this->root . '/src/Models/Customers.php: it exists; pass --force to replace it' . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testAnotherRunUpdatesTheBaseAndKeepsTheModel(): void
    {
        $this->runCommand(['users']);
        $this->createTables(UsersWithEmailMigration::class);
        $this->freshStreams();

        $status = $this->runCommand(['users']);

        $this->assertSame(0, $status);
        $this->assertStringContainsString(
            "    public ?string \$created = null;\n    public ?string \$email = null;\n",
            (string) file_get_contents($this->root . self::BASE)
        );
        $this->assertSame(
            'Updated ' . $this->root . self::BASE . PHP_EOL
            . 'No relations for users' . self::NO_KEYS . PHP_EOL
            . 'Kept ' . $this->root . self::USERS . ': it exists; pass --force to replace it' . PHP_EOL,
            $this->readStdout()
        );
    }

