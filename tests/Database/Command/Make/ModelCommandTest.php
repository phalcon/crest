    public function testTheRelationsReadTheRelatedRows(): void
    {
        // The "done when" of #51. The classes stay loaded in the PHP process,
        // so no other test may use the tables authors and books.
        $authors = $this->migration(AuthorsMigration::class);
        $books   = $this->migration(BooksMigration::class);
        $this->createTables($authors, $books);
        $authors->insert('ann');
        $books->insert('one', 1);

        $this->assertSame(0, $this->runCommand(['authors']));
        $this->assertSame(0, $this->runCommand(['books']));

        require $this->root . '/src/Models/Base/AuthorsBase.php';
        require $this->root . '/src/Models/Authors.php';
        require $this->root . '/src/Models/Base/BooksBase.php';
        require $this->root . '/src/Models/Books.php';

        // The models get their services from the default DI. An earlier test
        // can have made the default DI, so the test sets the DI of the front.
        Di::setDefault((new DatabaseFront())->boot());

        /** @var class-string<Model> $class */
        $class = Config::discover($this->root)->namespaceFor('model') . '\\Books';
        $book  = $class::findFirst();

        $this->assertInstanceOf(Model::class, $book);

        // getRelated() finds the relation by its alias, as $book->Author does.
        $author = $book->getRelated('Author');

        $this->assertInstanceOf(Model::class, $author);
        $this->assertSame(['id' => 1, 'name' => 'ann'], $author->toArray());

        $books = $author->getRelated('Books');

        $this->assertInstanceOf(ResultsetInterface::class, $books);
        $this->assertSame([['id' => 1, 'title' => 'one', 'author_id' => 1]], $books->toArray());
    }

