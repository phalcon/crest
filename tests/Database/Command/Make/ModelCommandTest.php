    public function testForceReplacesTheModel(): void
    {
        $this->runCommand(['users']);
        file_put_contents($this->root . self::USERS, 'mine');
        $this->freshStreams();

        $status = $this->runCommand(['users', '--force']);

        $this->assertSame(0, $status);
        $this->assertSame($this->wholeModel(), (string) file_get_contents($this->root . self::USERS));
        $this->assertSame(
            'No relations for users' . self::NO_KEYS . PHP_EOL . 'Created ' . $this->root . self::USERS . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testTheModelReadsARow(): void
    {
        // The "done when" of #50. The classes stay loaded in the PHP process,
        // so no other test may use the table members.
        $members = $this->migration(MembersMigration::class);
        $this->createTables($members);
        $members->insert('ann', 1.5);

        $status = $this->runCommand(['members']);

        $this->assertSame(0, $status);

        require $this->root . '/src/Models/Base/MembersBase.php';
        require $this->root . '/src/Models/Members.php';

        // The model gets its services from the default DI. An earlier test
        // can have made the default DI, so the test sets the DI of the front.
        Di::setDefault((new DatabaseFront())->boot());

        /** @var class-string<Model> $class */
        $class = Config::discover($this->root)->namespaceFor('model') . '\\Members';
        $row   = $class::findFirst();

        $this->assertInstanceOf(Model::class, $row);
        $this->assertSame(['id' => 1, 'name' => 'ann', 'score' => 1.5], $row->toArray());
    }

