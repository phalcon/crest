declare(strict_types=1);

namespace Crest\Tests\Database\Command\Make;

use Crest\Tests\Database\AbstractDatabaseTestCase;
use Crest\Tests\Support\Migrations\CustomerNamesViewMigration;
use Crest\Tests\Support\Migrations\CustomersMigration;
use Crest\Tests\Support\Migrations\InvoicesMigration;
use Crest\Tests\Support\Migrations\OddMigration;
use Crest\Tests\Support\Migrations\UserProfilesDashMigration;
use Crest\Tests\Support\Migrations\UsersMigration;
use Crest\Tests\Support\Project\DatabaseFront;
use Crest\Tests\Support\RunsMakeModel;
use Phalcon\Di\Di;

use function file_get_contents;
use function file_put_contents;
use function mkdir;
use function str_replace;

use const PHP_EOL;

/**
 * make:model --all writes a model for each table, with a heading for each
 * table and a summary (#52, spec 3.4). The tests run on each driver:
 * DatabaseFront gives the database of the suite. A test starts with no
 * tables.
 *
 * @group mysql
 * @group pgsql
 * @group sqlite
 */
final class ModelCommandAllTest extends AbstractDatabaseTestCase
{
    use RunsMakeModel;

    /**
     * The end of the line for a table with no keys, after "No relations for <table>".
     */
    private const NO_KEYS = ': the table has no foreign keys, and no foreign keys point to it. '
        . 'Relations come only from foreign keys.';

    protected function setUp(): void
    {
        parent::setUp();
        $this->startScratchProject('make-model-all');
        $this->front(DatabaseFront::class);
    }

    protected function tearDown(): void
    {
        // A boot makes a DI, and the first DI of the process is the default.
        Di::reset();
        $this->endScratchProject();
        parent::tearDown();
    }

    public function testABaseWithoutTheMarkerIsNotAFailure(): void
    {
        $this->createTables(UsersMigration::class);
        mkdir($this->root . '/src/Models/Base', 0o775, true);
        file_put_contents($this->model('Base/UsersBase.php'), '<?php // mine');

        $status = $this->runCommand(['--all']);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Table users' . PHP_EOL
            . 'Kept ' . $this->model('Base/UsersBase.php')
            . ': it has no "Generated by crest." line, so crest does not change it' . PHP_EOL
            . 'No relations for users' . self::NO_KEYS . PHP_EOL
            . 'Created ' . $this->model('Users.php') . PHP_EOL
            . PHP_EOL
            . '1 table: 1 model created, 0 kept, 0 failed.' . PHP_EOL,
            $this->readStdout()
        );
        $this->assertSame('<?php // mine', (string) file_get_contents($this->model('Base/UsersBase.php')));
    }

    public function testABrokenAttributeFailsOnlyItsTable(): void
    {
        // An attribute with only the key stops the read of the base of
        // invoices. invoices fails, and its base does not change. The
        // hasMany() of customers needs the names of invoices, so crest skips
        // it (#53, spec 3.2) and drops its alias attribute (#51). The
        // attribute is on line 16 of the base.
        $this->createTables(CustomersMigration::class, InvoicesMigration::class);
        $this->runCommand(['--all']);

        $baseFile = $this->model('Base/InvoicesBase.php');
        $broken   = str_replace(", alias: 'Customer'", '', (string) file_get_contents($baseFile));
        $reason   = $baseFile . ', line 16: a RelationAlias attribute needs two plain strings '
            . '(single quotes, or double quotes with no backslash), the key and the alias';

        file_put_contents($baseFile, $broken);
        $this->freshStreams();

        $status = $this->runCommand(['--all']);

        $this->assertSame(1, $status);
        $this->assertSame(
            'Table customers' . PHP_EOL
            . 'Updated ' . $this->model('Base/CustomersBase.php') . PHP_EOL
            . 'Skipped the relation hasMany invoices(customer_id) -> customers(id): ' . $reason . PHP_EOL
            . "Dropped the alias Invoices of 'hasMany invoices(customer_id) -> customers(id)': "
            . 'crest skips the relation' . PHP_EOL
            . 'Kept ' . $this->model('Customers.php') . ': it exists; pass --force to replace it' . PHP_EOL
            . PHP_EOL
            . 'Table invoices' . PHP_EOL
            . 'Failed: ' . $reason . PHP_EOL
            . PHP_EOL
            . '2 tables: 0 models created, 1 kept, 1 failed.' . PHP_EOL
            . 'Failed tables:' . PHP_EOL
            . '  invoices: ' . $reason . PHP_EOL,
            $this->readStdout()
        );
        $this->assertSame('', $this->readStderr());
        $this->assertSame($broken, (string) file_get_contents($baseFile));
    }

    public function testANameThatGivesNoClassFails(): void
    {
        $this->createTables(UserProfilesDashMigration::class, UsersMigration::class);

        $status = $this->runCommand(['--all']);
        $reason = "'user-profiles' gives no usable class name; expected a table name like 'users' or 'user_profiles'";

        $this->assertSame(1, $status);
        $this->assertSame(
            'Table user-profiles' . PHP_EOL
            . 'Failed: ' . $reason . PHP_EOL
            . PHP_EOL
            . 'Table users' . PHP_EOL
            . 'Created ' . $this->model('Base/UsersBase.php') . PHP_EOL
            . 'No relations for users' . self::NO_KEYS . PHP_EOL
            . 'Created ' . $this->model('Users.php') . PHP_EOL
            . PHP_EOL
            . '2 tables: 1 model created, 0 kept, 1 failed.' . PHP_EOL
            . 'Failed tables:' . PHP_EOL
            . '  user-profiles: ' . $reason . PHP_EOL,
            $this->readStdout()
        );
        $this->assertSame('', $this->readStderr());
    }

    public function testAnEmptyDatabaseHasNoTablesToWrite(): void
    {
        $status = $this->runCommand(['--all']);

        $this->assertSame(0, $status);
        $this->assertSame('No tables to write.' . PHP_EOL, $this->readStdout());
        $this->assertSame('', $this->readStderr());
        $this->assertDirectoryDoesNotExist($this->root . '/src/Models');
    }

    public function testAnExcludedTableKeepsItsRelation(): void
    {
        $this->createTables(CustomersMigration::class, InvoicesMigration::class);

        $status = $this->runCommand(['--all', '--exclude=invoices']);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Table customers' . PHP_EOL
            . 'Created ' . $this->model('Base/CustomersBase.php') . PHP_EOL
            . 'Created ' . $this->model('Customers.php') . PHP_EOL
            . PHP_EOL
            . '1 table: 1 model created, 0 kept, 0 failed.' . PHP_EOL,
            $this->readStdout()
        );
        $this->assertFileDoesNotExist($this->model('Invoices.php'));
        $this->assertStringContainsString(
            "        \$this->hasMany(\n"
            . "            'id',\n"
            . "            \\App\\Models\\Invoices::class,\n"
            . "            'customer_id',\n"
            . "            ['alias' => 'Invoices']\n"
            . "        );\n",
            (string) file_get_contents($this->model('Base/CustomersBase.php'))
        );
    }

    public function testAnExcludedViewGivesANote(): void
    {
        $this->createTables(CustomersMigration::class, CustomerNamesViewMigration::class);

        $status = $this->runCommand(['--all', '--exclude=customer_names']);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Note: customer_names is a view; --all writes no models for views' . PHP_EOL
            . 'Table customers' . PHP_EOL
            . 'Created ' . $this->model('Base/CustomersBase.php') . PHP_EOL
            . 'No relations for customers' . self::NO_KEYS . PHP_EOL
            . 'Created ' . $this->model('Customers.php') . PHP_EOL
            . PHP_EOL
            . '1 table: 1 model created, 0 kept, 0 failed.' . PHP_EOL,
            $this->readStdout()
        );
        $this->assertFileDoesNotExist($this->model('CustomerNames.php'));
    }

    public function testAnUnknownExcludeNameStops(): void
    {
        // The spaces go, a name given two times counts one time, and the
        // error names all the unknown names.
        $this->createTables(UsersMigration::class);

        $this->assertStops(
            ['--all', '--exclude=nope, users,nope,other'],
            '--exclude: the database has no table nope, other'
        );
    }

    public function testASecondRunKeepsTheModels(): void
    {
        // The "done when" of #52.
        $this->createTables(CustomersMigration::class, InvoicesMigration::class, UsersMigration::class);
        $this->runCommand(['--all']);
        $this->freshStreams();

        $status = $this->runCommand(['--all']);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Table customers' . PHP_EOL
            . 'Kept ' . $this->model('Customers.php') . ': it exists; pass --force to replace it' . PHP_EOL
            . PHP_EOL
            . 'Table invoices' . PHP_EOL
            . 'Kept ' . $this->model('Invoices.php') . ': it exists; pass --force to replace it' . PHP_EOL
            . PHP_EOL
            . 'Table users' . PHP_EOL
            . 'No relations for users' . self::NO_KEYS . PHP_EOL
            . 'Kept ' . $this->model('Users.php') . ': it exists; pass --force to replace it' . PHP_EOL
            . PHP_EOL
            . '3 tables: 0 models created, 3 kept, 0 failed.' . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testATableThatCannotBeReadFails(): void
    {
        // The column `first name` of odd is not a property name. crest
        // writes no file for odd, and writes the other tables.
        $this->createTables(CustomersMigration::class, OddMigration::class, UsersMigration::class);

        $status = $this->runCommand(['--all']);
        $reason = "column 'first name' of table 'odd' is not a usable property name; "
            . 'give it one with --property="first name=<name>"';

        $this->assertSame(1, $status);
        $this->assertSame(
            'Table customers' . PHP_EOL
            . 'Created ' . $this->model('Base/CustomersBase.php') . PHP_EOL
            . 'No relations for customers' . self::NO_KEYS . PHP_EOL
            . 'Created ' . $this->model('Customers.php') . PHP_EOL
            . PHP_EOL
            . 'Table odd' . PHP_EOL
            . 'Failed: ' . $reason . PHP_EOL
            . PHP_EOL
            . 'Table users' . PHP_EOL
            . 'Created ' . $this->model('Base/UsersBase.php') . PHP_EOL
            . 'No relations for users' . self::NO_KEYS . PHP_EOL
            . 'Created ' . $this->model('Users.php') . PHP_EOL
            . PHP_EOL
            . '3 tables: 2 models created, 0 kept, 1 failed.' . PHP_EOL
            . 'Failed tables:' . PHP_EOL
            . '  odd: ' . $reason . PHP_EOL,
            $this->readStdout()
        );
        $this->assertSame('', $this->readStderr());
        $this->assertFileDoesNotExist($this->model('Base/OddBase.php'));
        $this->assertFileDoesNotExist($this->model('Odd.php'));
    }

    public function testEachTableGetsAModelAndASummary(): void
    {
        $this->createTables(CustomersMigration::class, InvoicesMigration::class, UsersMigration::class);

        $status = $this->runCommand(['--all']);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Table customers' . PHP_EOL
            . 'Created ' . $this->model('Base/CustomersBase.php') . PHP_EOL
            . 'Created ' . $this->model('Customers.php') . PHP_EOL
            . PHP_EOL
            . 'Table invoices' . PHP_EOL
            . 'Created ' . $this->model('Base/InvoicesBase.php') . PHP_EOL
            . 'Created ' . $this->model('Invoices.php') . PHP_EOL
            . PHP_EOL
            . 'Table users' . PHP_EOL
            . 'Created ' . $this->model('Base/UsersBase.php') . PHP_EOL
            . 'No relations for users' . self::NO_KEYS . PHP_EOL
            . 'Created ' . $this->model('Users.php') . PHP_EOL
            . PHP_EOL
            . '3 tables: 3 models created, 0 kept, 0 failed.' . PHP_EOL,
            $this->readStdout()
        );
        $this->assertSame('', $this->readStderr());
    }

    public function testForceReplacesTheModels(): void
    {
        $this->createTables(UsersMigration::class);
        $this->runCommand(['--all']);
        file_put_contents($this->model('Users.php'), 'mine');
        $this->freshStreams();

        $status = $this->runCommand(['--all', '--force']);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Table users' . PHP_EOL
            . 'No relations for users' . self::NO_KEYS . PHP_EOL
            . 'Created ' . $this->model('Users.php') . PHP_EOL
            . PHP_EOL
            . '1 table: 1 model created, 0 kept, 0 failed.' . PHP_EOL,
            $this->readStdout()
        );
        $this->assertStringContainsString(
            "final class Users extends UsersBase\n",
            (string) file_get_contents($this->model('Users.php'))
        );
    }

    /**
     * A file in the `model` path of the scratch project.
     */
    private function model(string $file): string
    {
        return $this->root . '/src/Models/' . $file;
    }
}
