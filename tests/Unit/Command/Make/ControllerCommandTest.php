declare(strict_types=1);

namespace Crest\Tests\Unit\Command\Make;

use Crest\Command\Make\ControllerCommand;
use Crest\Generator\ArtifactWriter;
use Crest\Generator\Stub;
use Crest\Tests\Support\GeneratesInAScratchProject;
use PHPUnit\Framework\TestCase;

use function file_get_contents;
use function file_put_contents;
use function mkdir;
use function unlink;

use const PHP_EOL;

/**
 * make:controller writes two files: the base that crest owns, and the
 * controller that the developer owns. These tests hold the rules of the two
 * files (spec 3.2) and the output of each case.
 */
final class ControllerCommandTest extends TestCase
{
    use GeneratesInAScratchProject;

    private const BASE = '/src/Controllers/Base/CrestControllerBase.php';

    private const USERS = '/src/Controllers/UsersController.php';

    protected function setUp(): void
    {
        $this->startScratchProject('make-controller');
        $this->writeCrestPhp("['flavor' => 'mvc']");
    }

    protected function tearDown(): void
    {
        $this->endScratchProject();
    }

    /**
     * The name as typed, and the class that it gives.
     *
     * @return iterable<string, array{string, string}>
     */
    public static function doubledSuffixes(): iterable
    {
        yield 'another case' => ['Usercontroller', 'UsercontrollerController'];
        yield 'all uppercase' => ['UserCONTROLLER', 'UserCONTROLLERController'];
        yield 'two times' => ['UserControllerController', 'UserControllerController'];
    }

    /**
     * @return iterable<string, array{string, string}>
     */
    public static function routes(): iterable
    {
        yield 'one word' => ['Users', 'users'];
        yield 'two words' => ['UserProfiles', 'user-profiles'];
        yield 'an acronym' => ['APIKeys', 'a-p-i-keys'];
        yield 'a name outside ASCII' => ['Ünits', 'Ünits'];
    }

    /**
     * The name as typed, and the class that it gives.
     *
     * @return iterable<string, array{string, string}>
     */
    public static function unreachableNames(): iterable
    {
        yield 'a lowercase first letter' => ['users', 'usersController'];
        yield 'an underscore' => ['User_Profiles', 'User_ProfilesController'];
        yield 'only the suffix' => ['Controller', 'Controller'];
    }

    public function testABaseWithoutTheMarkerIsKeptAndTheControllerIsStillWritten(): void
    {
        mkdir($this->root . '/src/Controllers/Base', 0o775, true);
        file_put_contents($this->root . self::BASE, '<?php // mine');

        $status = $this->runCommand(['Users']);

        $this->assertSame(0, $status);
        $this->assertSame('<?php // mine', (string) file_get_contents($this->root . self::BASE));
        $this->assertFileExists($this->root . self::USERS);
        $this->assertStringStartsWith(
            'Kept ' . $this->root . self::BASE
            . ': it has no "Generated by crest." line, so crest does not change it' . PHP_EOL
            . 'Created ' . $this->root . self::USERS . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testABaseWithTheMarkerIsUpdated(): void
    {
        $this->runCommand(['Users']);
        file_put_contents($this->root . self::BASE, '<?php // ' . ArtifactWriter::MARKER . ' old');
        $this->freshStreams();

        $status = $this->runCommand(['Users']);

        $this->assertSame(0, $status);
        $this->assertSame($this->wholeBase(), (string) file_get_contents($this->root . self::BASE));
        $this->assertSame(
            'Updated ' . $this->root . self::BASE . PHP_EOL
            . 'Kept ' . $this->root . self::USERS . ': it exists; pass --force to replace it' . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testADeclaredControllerPathIsUsed(): void
    {
        // A project that keeps its classes in app/.
        $this->writeComposerJson(['Shop\\' => 'app/']);
        $this->writeCrestPhp("['flavor' => 'mvc', 'paths' => ['controller' => 'app/Controllers']]");

        $status = $this->runCommand(['Users']);

        $this->assertSame(0, $status);
        $this->assertStringContainsString(
            "namespace Shop\\Controllers\\Base;\n",
            (string) file_get_contents($this->root . '/app/Controllers/Base/CrestControllerBase.php')
        );
        $this->assertStringContainsString(
            "use Shop\\Controllers\\Base\\CrestControllerBase;\n",
            (string) file_get_contents($this->root . '/app/Controllers/UsersController.php')
        );
    }

    public function testAMissingBaseIsWrittenWhenTheControllerExists(): void
    {
        $this->runCommand(['Users']);
        unlink($this->root . self::BASE);
        $this->freshStreams();

        $status = $this->runCommand(['Users']);

        $this->assertSame(0, $status);
        $this->assertSame($this->wholeBase(), (string) file_get_contents($this->root . self::BASE));
        $this->assertSame(
            'Created ' . $this->root . self::BASE . PHP_EOL
            . 'Kept ' . $this->root . self::USERS . ': it exists; pass --force to replace it' . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testAnAdrProjectGetsTheFlavorError(): void
    {
        $this->writeCrestPhp();

        $status = $this->runCommand(['Users']);

        $this->assertSame(1, $status);
        $this->assertSame(
            "crest: make:controller does not support the 'adr' flavor of this project; it supports: mvc" . PHP_EOL,
            $this->readStderr()
        );
        $this->assertDirectoryDoesNotExist($this->root . '/src/Controllers');
    }

    /**
     * @dataProvider unreachableNames
     */
    public function testANameThatNoUrlReachesStopsTheCommand(string $name, string $class): void
    {
        $status = $this->runCommand([$name]);

        $this->assertSame(1, $status);
        $this->assertSame(
            "crest: '" . $name . "' gives " . $class
            . ", which the dispatcher cannot find from a URL; use a name like 'Users'" . PHP_EOL,
            $this->readStderr()
        );
        $this->assertDirectoryDoesNotExist($this->root . '/src/Controllers');
    }

    public function testAnExistingControllerIsKept(): void
    {
        // The base did not change, so it has no line. The guidance is only
        // for a controller that crest writes.
        $this->runCommand(['Users']);
        file_put_contents($this->root . self::USERS, 'mine');
        $this->freshStreams();

        $status = $this->runCommand(['Users']);

        $this->assertSame(0, $status);
        $this->assertSame('mine', (string) file_get_contents($this->root . self::USERS));
        $this->assertSame(
            'Kept ' . $this->root . self::USERS . ': it exists; pass --force to replace it' . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testAnUnusableNameIsReported(): void
    {
        $status = $this->runCommand(['Admin/Sample']);

        $this->assertSame(1, $status);
        $this->assertStringContainsString("'Admin/Sample' is not a usable class name", $this->readStderr());
    }

    public function testAPublishedBaseWithoutTheMarkerGivesNoNoteWhenItIsTheSame(): void
    {
        // The file is the same as the rendered stub on each run, so crest has
        // nothing to say about it.
        mkdir($this->root . '/resources/stubs/mvc', 0o775, true);
        file_put_contents(
            Stub::overridePath($this->root, 'mvc', 'controller-base'),
            "<?php\n\nnamespace {{ namespace }};\n\n"
            . "abstract class {{ class }} extends \\Phalcon\\Mvc\\Controller\n{\n}\n"
        );
        $this->runCommand(['Users']);
        $this->freshStreams();

        $status = $this->runCommand(['Users']);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Kept ' . $this->root . self::USERS . ': it exists; pass --force to replace it' . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testASecondControllerWritesOnlyItself(): void
    {
        $this->runCommand(['Users']);
        $this->freshStreams();

        $status = $this->runCommand(['Orders']);

        $this->assertSame(0, $status);
        $this->assertStringStartsWith(
            'Created ' . $this->root . '/src/Controllers/OrdersController.php' . PHP_EOL
            . 'The dispatcher finds it',
            $this->readStdout()
        );
    }

    /**
     * @dataProvider doubledSuffixes
     */
    public function testASuffixTwiceStopsTheCommand(string $name, string $class): void
    {
        $status = $this->runCommand([$name]);

        $this->assertSame(1, $status);
        $this->assertSame(
            "crest: '" . $name . "' gives " . $class
            . ", with 'Controller' twice; type the name without 'Controller'" . PHP_EOL,
            $this->readStderr()
        );
        $this->assertDirectoryDoesNotExist($this->root . '/src/Controllers');
    }

    public function testDefinitionNamesItself(): void
    {
        $definition = (new ControllerCommand())->define();

        $this->assertSame('make:controller', $definition->getName());
        $this->assertSame('Create an MVC controller', $definition->getDescription());
    }

    public function testForceReplacesTheControllerButNotABaseWithoutTheMarker(): void
    {
        $this->runCommand(['Users']);
        file_put_contents($this->root . self::USERS, 'mine');
        file_put_contents($this->root . self::BASE, '<?php // mine');
        $this->freshStreams();

        $status = $this->runCommand(['Users', '--force']);

        $this->assertSame(0, $status);
        $this->assertSame($this->wholeController(), (string) file_get_contents($this->root . self::USERS));
        $this->assertSame('<?php // mine', (string) file_get_contents($this->root . self::BASE));
        $this->assertStringContainsString(
            'Created ' . $this->root . self::USERS . PHP_EOL . 'The dispatcher finds it',
            $this->readStdout()
        );
    }

    public function testNameArgumentIsRequired(): void
    {
        $status = $this->runCommand([]);

        $this->assertSame(1, $status);
        $this->assertStringContainsString("missing required argument 'name'", $this->readStderr());
    }

    public function testTheBaseCarriesTheMarker(): void
    {
        // renderOwned() writes the base again only with this text in it.
        $this->runCommand(['Users']);

        $this->assertStringContainsString(
            ArtifactWriter::MARKER,
            (string) file_get_contents($this->root . self::BASE)
        );
    }

    public function testTheFirstRunWritesTheBaseTheControllerAndTheGuidance(): void
    {
        // Asserted whole: the guidance is the wiring that the developer copies,
        // and the blank lines around the snippet are part of it.
        $status = $this->runCommand(['Users']);

        $expected = 'Created ' . $this->root . self::BASE . PHP_EOL
            . 'Created ' . $this->root . self::USERS . PHP_EOL
            . 'The dispatcher finds it only when its default namespace is this namespace:' . PHP_EOL
            . PHP_EOL
            . "    \$dispatcher->setDefaultNamespace('App\\Controllers');" . PHP_EOL
            . PHP_EOL
            . 'With the default routes, GET /users runs indexAction(). Its view is users/index'
            . ' in your views directory.' . PHP_EOL;

        $this->assertSame(0, $status);
        $this->assertSame($expected, $this->readStdout());
    }

    /**
     * @dataProvider routes
     */
    public function testTheGuidanceNamesTheRouteAndTheView(string $name, string $route): void
    {
        $status = $this->runCommand([$name]);

        $this->assertSame(0, $status);
        $this->assertStringContainsString(
            'GET /' . $route . ' runs indexAction(). Its view is ' . $route . '/index',
            $this->readStdout()
        );
    }

    public function testTheNameBaseDoesNotCollideWithTheBaseFolder(): void
    {
        $status = $this->runCommand(['Base']);

        $this->assertSame(0, $status);
        $this->assertFileExists($this->root . '/src/Controllers/BaseController.php');
        $this->assertFileExists($this->root . self::BASE);
    }

    public function testTheSuffixIsNotDoubledWhenTheUserSuppliesIt(): void
    {
        $status = $this->runCommand(['UserController']);

        $this->assertSame(0, $status);
        $this->assertFileExists($this->root . '/src/Controllers/UserController.php');
        $this->assertFileDoesNotExist($this->root . '/src/Controllers/UserControllerController.php');
    }

    public function testTheWholeBaseIsRendered(): void
    {
        // Asserted whole: this is generated code that nobody reviews.
        $this->runCommand(['Users']);

        $this->assertSame($this->wholeBase(), (string) file_get_contents($this->root . self::BASE));
    }

    public function testTheWholeControllerIsRendered(): void
    {
        $this->runCommand(['Users']);

        $this->assertSame($this->wholeController(), (string) file_get_contents($this->root . self::USERS));
    }

    /**
     * Empty streams for the output of the next run.
     */
    private function freshStreams(): void
    {
        $this->closeStreams();
        $this->captureStreams();
    }

    /**
     * @param list<string> $arguments
     */
    private function runCommand(array $arguments): int
    {
        return $this->runProjectCommand('make:controller', ControllerCommand::class, $arguments);
    }

    private function wholeBase(): string
    {
        return "<?php\n"
            . "\n"
            . "declare(strict_types=1);\n"
            . "\n"
            . "namespace App\\Controllers\\Base;\n"
            . "\n"
            . "use Phalcon\\Mvc\\Controller;\n"
            . "\n"
            . "/**\n"
            . " * Generated by crest. Do not edit this file: crest writes it again when you\n"
            . " * run make:controller. Put the code that your controllers share into your own\n"
            . " * class.\n"
            . " */\n"
            . "abstract class CrestControllerBase extends Controller\n"
            . "{\n"
            . "}\n";
    }

    private function wholeController(): string
    {
        return "<?php\n"
            . "\n"
            . "declare(strict_types=1);\n"
            . "\n"
            . "namespace App\\Controllers;\n"
            . "\n"
            . "use App\\Controllers\\Base\\CrestControllerBase;\n"
            . "\n"
            . "final class UsersController extends CrestControllerBase\n"
            . "{\n"
            . "    public function indexAction(): void\n"
            . "    {\n"
            . "    }\n"
            . "}\n";
    }
}
