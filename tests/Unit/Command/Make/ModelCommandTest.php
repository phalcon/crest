declare(strict_types=1);

namespace Crest\Tests\Unit\Command\Make;

use Crest\Command\Make\ModelCommand;
use Crest\Project\Config;
use Crest\Tests\Support\GeneratesInAScratchProject;
use Crest\Tests\Support\Project\DatabaseFront;
use Crest\Tests\Support\Project\FailingDatabaseFront;
use Crest\Tests\Support\Project\FailingFront;
use Crest\Tests\Support\Project\NoDatabaseFront;
use Crest\Tests\Support\Project\WrongContainerFront;
use Crest\Tests\Support\Project\WrongDatabaseFront;
use PDO;
use Phalcon\Di\Di;
use Phalcon\Mvc\Model;
use PHPUnit\Framework\TestCase;

use function file_get_contents;
use function file_put_contents;
use function mkdir;

use const PHP_EOL;

/**
 * make:model reads a table through the `db` service of the project, and writes
 * the base that crest owns and the model that the developer owns (spec 3).
 * Each test has an SQLite file with the table `users` in the scratch project.
 */
final class ModelCommandTest extends TestCase
{
    use GeneratesInAScratchProject;

    private const BASE = '/src/Models/Base/UsersBase.php';

    private const USERS = '/src/Models/Users.php';

    private const USERS_TABLE = 'CREATE TABLE users (id INTEGER PRIMARY KEY AUTOINCREMENT, '
        . 'name VARCHAR(50) NOT NULL, score REAL, price DECIMAL(10,2), created DATETIME)';

    protected function setUp(): void
    {
        $this->startScratchProject('make-model');
        $this->front(DatabaseFront::class);
        $this->table(self::USERS_TABLE);
    }

    protected function tearDown(): void
    {
        // A boot makes a DI, and the first DI of the process is the default.
        Di::reset();
        $this->endScratchProject();
    }

    public function testABaseWithoutTheMarkerIsKept(): void
    {
        mkdir($this->root . '/src/Models/Base', 0o775, true);
        file_put_contents($this->root . self::BASE, '<?php // mine');

        $status = $this->runCommand(['users']);

        $this->assertSame(0, $status);
        $this->assertSame('<?php // mine', (string) file_get_contents($this->root . self::BASE));
        $this->assertSame(
            'Kept ' . $this->root . self::BASE
            . ': it has no "Generated by crest." line, so crest does not change it' . PHP_EOL
            . 'Created ' . $this->root . self::USERS . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testAColumnThatIsNotAPropertyNameStops(): void
    {
        $this->table('CREATE TABLE odd (id INTEGER PRIMARY KEY, "first name" TEXT)');

        $this->assertStops(['odd'], "column 'first name' of table 'odd' is not a usable property name");
    }

    public function testAColumnWithTheNameOfAModelPropertyStops(): void
    {
        // A typed property with this name is a fatal error in the base.
        $this->table('CREATE TABLE boxes (id INTEGER PRIMARY KEY, container TEXT)');

        $this->assertStops(
            ['boxes'],
            "column 'container' of table 'boxes' has the name of a property of Phalcon\\Mvc\\Model"
        );
    }

    public function testAContainerThatIsNotADiStops(): void
    {
        $this->front(WrongContainerFront::class);

        $this->assertStops(
            ['users'],
            'stdClass is not a Phalcon DI container; make:model needs the DI of an MVC project'
        );
    }

    public function testADbServiceThatFailsStops(): void
    {
        $this->front(FailingDatabaseFront::class);

        $this->assertStops(
            ['users'],
            "the 'db' service failed: SQLSTATE[HY000] [14] unable to open database file"
        );
    }

    public function testADbServiceThatIsNotAnAdapterStops(): void
    {
        $this->front(WrongDatabaseFront::class);

        $this->assertStops(['users'], "the 'db' service is stdClass, not a Phalcon database adapter");
    }

    public function testADeclaredModelPathIsUsed(): void
    {
        // A project that keeps its classes in app/. A stub with a fixed
        // namespace fails here.
        $this->writeComposerJson(['Shop\\' => 'app/']);
        $this->writeCrestPhp(
            "['flavor' => 'mvc', 'bootstrap' => \\" . DatabaseFront::class . '::class, '
            . "'paths' => ['model' => 'app/Entities']]"
        );

        $status = $this->runCommand(['users']);

        $this->assertSame(0, $status);
        $this->assertStringContainsString(
            "namespace Shop\\Entities\\Base;\n",
            (string) file_get_contents($this->root . '/app/Entities/Base/UsersBase.php')
        );
        $this->assertStringContainsString(
            "use Shop\\Entities\\Base\\UsersBase;\n",
            (string) file_get_contents($this->root . '/app/Entities/Users.php')
        );
    }

    public function testAMissingTableStops(): void
    {
        $this->assertStops(['nothing'], "table 'nothing' was not found in the database of the 'db' service");
    }

    public function testAModelPathWithNoNamespaceStopsBeforeTheBoot(): void
    {
        // FailingFront fails to boot. The namespace check runs first, so its
        // error is the one on stderr.
        $this->writeCrestPhp(
            "['flavor' => 'mvc', 'bootstrap' => \\" . FailingFront::class . '::class, '
            . "'paths' => ['model' => 'models']]"
        );

        $this->assertStops(['users'], "no psr-4 autoload entry covers 'models'");
    }

    public function testAnAdrProjectStops(): void
    {
        $this->writeCrestPhp();

        $this->assertStops(
            ['users'],
            "make:model does not support the 'adr' flavor of this project; it supports: mvc"
        );
    }

    public function testANameThatGivesNoClassStops(): void
    {
        // FailingFront fails to boot. The name check runs first, so its
        // error is the one on stderr.
        $this->front(FailingFront::class);

        $this->assertStops(
            ['user-profiles'],
            "'user-profiles' gives no usable class name; expected a table name like 'users' or 'user_profiles'"
        );
    }

    public function testAnotherRunUpdatesTheBaseAndKeepsTheModel(): void
    {
        $this->runCommand(['users']);
        $this->table('ALTER TABLE users ADD COLUMN email VARCHAR(100)');
        $this->freshStreams();

        $status = $this->runCommand(['users']);

        $this->assertSame(0, $status);
        $this->assertStringContainsString(
            "    public ?string \$created = null;\n    public ?string \$email = null;\n",
            (string) file_get_contents($this->root . self::BASE)
        );
        $this->assertSame(
            'Updated ' . $this->root . self::BASE . PHP_EOL
            . 'Kept ' . $this->root . self::USERS . ': it exists; pass --force to replace it' . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testAnUnchangedTableGivesOnlyTheKeptLine(): void
    {
        $this->runCommand(['users']);
        $this->freshStreams();

        $status = $this->runCommand(['users']);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Kept ' . $this->root . self::USERS . ': it exists; pass --force to replace it' . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testAReservedNameStops(): void
    {
        $this->front(FailingFront::class);

        $this->assertStops(['list'], "'list' gives the class List, but PHP reserves that name");
    }

    public function testATableNameWithUnderscoresKeepsItsSource(): void
    {
        $this->table('CREATE TABLE user_profiles (id INTEGER PRIMARY KEY AUTOINCREMENT)');

        $status = $this->runCommand(['user_profiles']);

        $this->assertSame(0, $status);
        $this->assertFileExists($this->root . '/src/Models/UserProfiles.php');

        $base = (string) file_get_contents($this->root . '/src/Models/Base/UserProfilesBase.php');

        $this->assertStringContainsString("abstract class UserProfilesBase extends Model\n", $base);
        $this->assertStringContainsString("        \$this->setSource('user_profiles');\n", $base);
    }

    public function testDefinitionNamesItself(): void
    {
        $definition = (new ModelCommand())->define();

        $this->assertSame('make:model', $definition->getName());
        $this->assertSame('Create an MVC model from a database table', $definition->getDescription());
    }

    public function testForceReplacesTheModel(): void
    {
        $this->runCommand(['users']);
        file_put_contents($this->root . self::USERS, 'mine');
        $this->freshStreams();

        $status = $this->runCommand(['users', '--force']);

        $this->assertSame(0, $status);
        $this->assertSame($this->wholeModel(), (string) file_get_contents($this->root . self::USERS));
        $this->assertSame('Created ' . $this->root . self::USERS . PHP_EOL, $this->readStdout());
    }

    public function testNoDbServiceStops(): void
    {
        $this->front(NoDatabaseFront::class);

        $this->assertStops(
            ['users'],
            "the project container has no 'db' service; register one with a provider (crest make:provider Db)"
        );
    }

    public function testTheModelReadsARow(): void
    {
        // The "done when" of #50. The classes stay loaded in the PHP process,
        // so no other test may use the table members.
        $this->table(
            'CREATE TABLE members (id INTEGER PRIMARY KEY AUTOINCREMENT, '
            . 'name VARCHAR(50) NOT NULL, score REAL)'
        );
        $this->table("INSERT INTO members (name, score) VALUES ('ann', 1.5)");

        $status = $this->runCommand(['members']);

        $this->assertSame(0, $status);

        require $this->root . '/src/Models/Base/MembersBase.php';
        require $this->root . '/src/Models/Members.php';

        // The model gets its services from the default DI. An earlier test
        // can have made the default DI, so the test sets the DI of the front.
        Di::setDefault((new DatabaseFront($this->root))->boot());

        /** @var class-string<Model> $class */
        $class = Config::discover($this->root)->namespaceFor('model') . '\\Members';
        $row   = $class::findFirst();

        $this->assertInstanceOf(Model::class, $row);
        $this->assertSame(['id' => 1, 'name' => 'ann', 'score' => 1.5], $row->toArray());
    }

    public function testTheOutputNamesBothFiles(): void
    {
        $status = $this->runCommand(['users']);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Created ' . $this->root . self::BASE . PHP_EOL
            . 'Created ' . $this->root . self::USERS . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testTheTableArgumentIsRequired(): void
    {
        $status = $this->runCommand([]);

        $this->assertSame(1, $status);
        $this->assertStringContainsString("missing required argument 'table'", $this->readStderr());
    }

    public function testTheWholeBaseIsRendered(): void
    {
        // Asserted whole: this is generated code that nobody reviews.
        $this->runCommand(['users']);

        $this->assertSame($this->wholeBase(), (string) file_get_contents($this->root . self::BASE));
    }

    public function testTheWholeModelIsRendered(): void
    {
        $this->runCommand(['users']);

        $this->assertSame($this->wholeModel(), (string) file_get_contents($this->root . self::USERS));
    }

    /**
     * The command stops with the error on stderr, and writes no file.
     *
     * @param list<string> $arguments
     */
    private function assertStops(array $arguments, string $error): void
    {
        $status = $this->runCommand($arguments);

        $this->assertSame(1, $status);
        $this->assertSame('crest: ' . $error . PHP_EOL, $this->readStderr());
        $this->assertDirectoryDoesNotExist($this->root . '/src/Models');
    }

    /**
     * Empty streams for the output of the next run.
     */
    private function freshStreams(): void
    {
        $this->closeStreams();
        $this->captureStreams();
    }

    /**
     * An MVC crest.php that names the front controller.
     *
     * @param class-string $class
     */
    private function front(string $class): void
    {
        $this->writeCrestPhp("['flavor' => 'mvc', 'bootstrap' => \\" . $class . '::class]');
    }

    /**
     * @param list<string> $arguments
     */
    private function runCommand(array $arguments): int
    {
        return $this->runProjectCommand('make:model', ModelCommand::class, $arguments);
    }

    /**
     * Runs SQL on the SQLite file of DatabaseFront.
     */
    private function table(string $sql): void
    {
        (new PDO('sqlite:' . $this->root . '/' . DatabaseFront::FILE))->exec($sql);
    }

    private function wholeBase(): string
    {
        return "<?php\n"
            . "\n"
            . "declare(strict_types=1);\n"
            . "\n"
            . "namespace App\\Models\\Base;\n"
            . "\n"
            . "use Phalcon\\Mvc\\Model;\n"
            . "\n"
            . "/**\n"
            . " * Generated by crest. Do not edit this file: crest writes it again when you\n"
            . " * run make:model users. Put your code into the model that extends it.\n"
            . " */\n"
            . "abstract class UsersBase extends Model\n"
            . "{\n"
            . "    public ?int \$id = null;\n"
            . "    public ?string \$name = null;\n"
            . "    public ?float \$score = null;\n"
            . "    public ?string \$price = null;\n"
            . "    public ?string \$created = null;\n"
            . "\n"
            . "    public function initialize(): void\n"
            . "    {\n"
            . "        \$this->setSource('users');\n"
            . "    }\n"
            . "}\n";
    }

    private function wholeModel(): string
    {
        return "<?php\n"
            . "\n"
            . "declare(strict_types=1);\n"
            . "\n"
            . "namespace App\\Models;\n"
            . "\n"
            . "use App\\Models\\Base\\UsersBase;\n"
            . "\n"
            . "final class Users extends UsersBase\n"
            . "{\n"
            . "    // If you add initialize(), call parent::initialize() first.\n"
            . "}\n";
    }
}
