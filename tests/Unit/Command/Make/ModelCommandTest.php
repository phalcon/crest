    use GeneratesInAScratchProject;

    private const BASE = '/src/Models/Base/UsersBase.php';

    private const CUSTOMERS_TABLE = 'CREATE TABLE customers (id INTEGER PRIMARY KEY AUTOINCREMENT, '
        . 'name VARCHAR(50) NOT NULL)';

    /**
     * The attribute of the relation of invoices, up to the value of the alias.
     */
    private const INVOICE_ATTRIBUTE = '#[\\Crest\\Attribute\\RelationAlias('
        . "'belongsTo invoices(customer_id) -> customers(id)', alias: ";

    private const INVOICES_TABLE = 'CREATE TABLE invoices (id INTEGER PRIMARY KEY AUTOINCREMENT, '
        . 'customer_id INTEGER NOT NULL REFERENCES customers(id), total DECIMAL(10,2))';

    /**
     * The end of the line for a table with no keys, after "No relations for <table>".
     */
    private const NO_KEYS = ': the table has no foreign keys, and no foreign keys point to it. '
        . 'Relations come only from foreign keys.';

    private const USERS = '/src/Models/Users.php';

    private const USERS_TABLE = 'CREATE TABLE users (id INTEGER PRIMARY KEY AUTOINCREMENT, '
        . 'name VARCHAR(50) NOT NULL, score REAL, price DECIMAL(10,2), created DATETIME)';

    protected function setUp(): void
    {
        $this->startScratchProject('make-model');
        $this->front(DatabaseFront::class);
        $this->table(self::USERS_TABLE);
    }

    protected function tearDown(): void
    {
        // A boot makes a DI, and the first DI of the process is the default.
        Di::reset();
        $this->endScratchProject();
    }

    public function testABaseWithoutTheMarkerIsKept(): void
    {
        mkdir($this->root . '/src/Models/Base', 0o775, true);
        file_put_contents($this->root . self::BASE, '<?php // mine');

        $status = $this->runCommand(['users']);

        $this->assertSame(0, $status);
        $this->assertSame('<?php // mine', (string) file_get_contents($this->root . self::BASE));
        $this->assertSame(
            'Kept ' . $this->root . self::BASE
            . ': it has no "Generated by crest." line, so crest does not change it' . PHP_EOL
            . 'No relations for users' . self::NO_KEYS . PHP_EOL
            . 'Created ' . $this->root . self::USERS . PHP_EOL,
            $this->readStdout()
        );
    }

    public function testABrokenAliasAttributeStops(): void
    {
        // An attribute with only the key stops the command before crest
        // writes a file, so the base and the model do not change. The
        // attribute is on line 16 of the base.
        $this->table(self::CUSTOMERS_TABLE);
        $this->table(self::INVOICES_TABLE);
        $this->runCommand(['invoices']);

        $baseFile = $this->root . '/src/Models/Base/InvoicesBase.php';
        $broken   = str_replace(", alias: 'Customer'", '', (string) file_get_contents($baseFile));
        $model    = (string) file_get_contents($this->root . '/src/Models/Invoices.php');

        file_put_contents($baseFile, $broken);
        $this->freshStreams();

        $status = $this->runCommand(['invoices']);

        $this->assertSame(1, $status);
        $this->assertSame(
            'crest: ' . $baseFile . ', line 16: a RelationAlias attribute needs two plain strings '
            . '(single quotes, or double quotes with no backslash), the key and the alias' . PHP_EOL,
            $this->readStderr()
        );
        $this->assertSame($broken, (string) file_get_contents($baseFile));
        $this->assertSame($model, (string) file_get_contents($this->root . '/src/Models/Invoices.php'));
    }

    public function testAChangedAliasIsKept(): void
    {
        // The developer changes the alias in the attribute of the base. The
        // next run writes the base again with that alias.
        $this->table(self::CUSTOMERS_TABLE);
        $this->table(self::INVOICES_TABLE);
        $this->runCommand(['invoices']);

        $baseFile = $this->root . '/src/Models/Base/InvoicesBase.php';
        $changed  = str_replace("alias: 'Customer'", "alias: 'Client'", (string) file_get_contents($baseFile));

        file_put_contents($baseFile, $changed);
        $this->freshStreams();

        $status = $this->runCommand(['invoices']);
        $base   = (string) file_get_contents($baseFile);

        $this->assertSame(0, $status);
        $this->assertSame(
            'Updated ' . $baseFile . PHP_EOL
            . 'Kept ' . $this->root . '/src/Models/Invoices.php: it exists; pass --force to replace it' . PHP_EOL,
            $this->readStdout()
        );
        $this->assertStringContainsString(self::INVOICE_ATTRIBUTE . "'Client')]\n", $base);
        $this->assertStringContainsString("            ['alias' => 'Client']\n", $base);
    }

