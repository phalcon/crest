    public function testTwoRelationsBothGoIntoTheBase(): void
    {
        // Each relation renders its own fragment, and the base gets all of
        // them.
        $this->table(
            'CREATE TABLE messages (id INTEGER PRIMARY KEY, recipient_id INTEGER REFERENCES users(id), '
            . 'sender_id INTEGER REFERENCES users(id))'
        );

        $this->runCommand(['users']);

        $base = (string) file_get_contents($this->root . self::BASE);

        $this->assertStringContainsString("            ['alias' => 'MessagesByRecipient']\n", $base);
        $this->assertStringContainsString("            ['alias' => 'MessagesBySender']\n", $base);
    }

    /**
     * The command stops with the error on stderr, and writes no file.
     *
     * @param list<string> $arguments
     */
    private function assertStops(array $arguments, string $error): void
    {
        $status = $this->runCommand($arguments);

        $this->assertSame(1, $status);
        $this->assertSame('crest: ' . $error . PHP_EOL, $this->readStderr());
        $this->assertDirectoryDoesNotExist($this->root . '/src/Models');
    }

    /**
     * Empty streams for the output of the next run.
     */
    private function freshStreams(): void
    {
        $this->closeStreams();
        $this->captureStreams();
    }

    /**
     * An MVC crest.php that names the front controller.
     *
     * @param class-string $class
     */
    private function front(string $class): void
    {
        $this->writeCrestPhp("['flavor' => 'mvc', 'bootstrap' => \\" . $class . '::class]');
    }

    /**
     * @param list<string> $arguments
     */
    private function runCommand(array $arguments): int
    {
        return $this->runProjectCommand('make:model', ModelCommand::class, $arguments);
    }

    /**
     * Runs SQL on the SQLite file of DatabaseFront.
     */
    private function table(string $sql): void
    {
        (new PDO('sqlite:' . $this->root . '/' . DatabaseFront::FILE))->exec($sql);
    }

